export const formatPrice = (amount: number, fromCurrency = 'USD', toCurrency = 'USD'): string => {
  const rateFrom = CURRENCY_RATES[fromCurrency] || 1.0;
  const rateTo = CURRENCY_RATES[toCurrency] || 1.0;
  const inUSD = amount / rateFrom;
  const converted = inUSD * rateTo;
  const symbol = CURRENCY_SYMBOLS[toCurrency] || toCurrency;

  if (toCurrency === 'INR') {
    // Indian numbering format (lakhs, crores)
    return `${symbol}${new Intl.NumberFormat('en-IN', { maximumFractionDigits: 0 }).format(Math.round(converted))}`;
  } else if (toCurrency === 'JPY') {
    return `${symbol}${new Intl.NumberFormat('ja-JP', { maximumFractionDigits: 0 }).format(Math.round(converted))}`;
  } else {
    return `${symbol}${new Intl.NumberFormat('en-US', { maximumFractionDigits: 0 }).format(Math.round(converted))}`;
  }
};

